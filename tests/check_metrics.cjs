const assert=require('assert/strict');
const M=require('../dashboard/metrics.js');
assert.equal(M.avg([0,2]),1);
assert.equal(M.avg([1,null]),null);
assert.equal(M.avg([]),null);
assert.equal(M.rank([1,2,2,3],2),50);
assert.equal(M.rank([null],2),null);
assert.equal(M.rank([1,2,3],4),100);
const rows=[{date:'2024-02-23',v:0},{date:'2024-03-01',v:2},{date:'2024-03-08',v:4}];
assert.equal(M.previous(rows,'2024-03-01').v,0);
assert.equal(M.previous(rows,'2024-03-02'),null);
assert.equal(M.windowMean(rows,'v',3),2);
assert.equal(M.windowMean(rows,'v',4),null);
assert.equal(M.windowMean([rows[0],rows[2]],'v',2),null);
assert.equal(M.windowMean([{date:'2024-03-01',v:null},rows[2]],'v',2),null);
assert.equal(M.value({tet:1,cwy:.9},'spread').toFixed(2),'10.00');
assert.equal(M.value({cwy:1,wti:0},'cwyRatio'),null);
assert.equal(M.exposure([50,50],[10,-10]),0);
assert.equal(M.exposure([2,1],[15,0]),10);
assert.equal(M.exposure([0,0],[10,10]),null);
assert.equal(M.exposure([-1,2],[10,10]),null);
assert.equal(M.exposure([1],[-101]),null);
assert.equal(M.shock(100,50,20,30,4),1.12);
assert.equal(M.shock(0,0,0,100,4),-2.8);
assert.equal(M.shock(0,0,0,0,0),null);
console.log('Analytical rules pass: missing data, exact dates, leap year, tied ranks, units and scenario signs.');
